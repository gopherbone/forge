"""Clearance calibration coupon. A plate with pegs and matching holes at a range of
per-side gaps, each gap embossed on the plate. Print it, test each pair, then
record the results with `forge calibrate`, which writes projects/_calibration/fits.yaml."""
from __future__ import annotations

from pathlib import Path

from .project import Project

GAPS = [0.05, 0.10, 0.15, 0.20, 0.25, 0.30, 0.40]

DESIGN = '''"""Clearance coupon (generated by forge coupon). Each column: a hole in the plate and a
loose peg, gap per side labelled. Test: does the peg press in, slide, or drop through?"""
from build123d import *
from forge.dsl import Design, Part

GAPS = {gaps}
D, PITCH, T = 8.0, 13.0, 4.0


def build(p):
    n = len(GAPS)
    plate = Box(PITCH * n + 6, 26, T, align=(Align.MIN, Align.MIN, Align.MIN))
    pegs = []
    for i, g in enumerate(GAPS):
        x = 3 + PITCH * i + PITCH / 2
        plate -= Pos(x, 9, 0) * Cylinder(D / 2 + g, T, align=(Align.CENTER, Align.CENTER, Align.MIN))
        label = Pos(x, 20.5, T - 0.4) * extrude(Text(f"{{g:.2f}}".lstrip("0"), 3.4, font_style=FontStyle.BOLD), 0.4)
        plate -= label
        peg = Pos(x, 40, 0) * (Cylinder(D / 2, 10, align=(Align.CENTER, Align.CENTER, Align.MIN))
                               + Pos(0, 0, 10) * Cylinder(D / 2 + 1.2, 2, align=(Align.CENTER, Align.CENTER, Align.MIN)))
        pegs.append(peg)
    return Design(parts=[Part("plate", plate, cosmetic=["+z"]),
                         Part("pegs", Compound(pegs), orient=(180, 0, 0), bodies=len(GAPS), notes="print head-down so the peg shank is clean")])
'''

SPEC = """title: Clearance coupon
summary: Pegs and holes at per-side gaps {gaps} mm. Print in the filament and settings you design with.
params: {{}}
printer:
  process: "0.20mm Standard @BBL X1C"
"""


def create(name: str = "_coupon") -> Project:
    proj = Project(name)
    proj.dir.mkdir(parents=True, exist_ok=True)
    (proj.dir / "design.py").write_text(DESIGN.format(gaps=GAPS))
    (proj.dir / "spec.yaml").write_text(SPEC.format(gaps=GAPS))
    (proj.dir / "journal.md").write_text("# Journal: clearance coupon\n")
    return proj


def calibrate(press: float, snug: float, sliding: float, loose: float, note: str = "") -> Path:
    import yaml
    from . import config
    p = config.PROJECTS / "_calibration" / "fits.yaml"
    p.parent.mkdir(parents=True, exist_ok=True)
    data = {"calibrated": True, "note": note,
            "fits": {"press": {"gap": press}, "snug": {"gap": snug}, "sliding": {"gap": sliding}, "loose": {"gap": loose},
                     "print_in_place": {"gap": max(loose + 0.05, 0.3)}}}
    p.write_text(yaml.safe_dump(data, sort_keys=False))
    return p
